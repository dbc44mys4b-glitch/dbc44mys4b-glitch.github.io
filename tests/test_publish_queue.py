import json
from random import Random
from pathlib import Path
import struct
import subprocess
import sys
from tempfile import TemporaryDirectory
import unittest
from datetime import datetime
from zoneinfo import ZoneInfo
import zlib

ROOT = Path(__file__).resolve().parents[1]
SLUG = "unpublished-fixture-article"


def png(pixel):
    def chunk(kind, data):
        return struct.pack(">I", len(data)) + kind + data + struct.pack(">I", zlib.crc32(kind + data))

    width, height = 1200, 630
    random = Random(pixel)
    rows = b"".join(b"\0" + random.randbytes(width) for _ in range(height))
    return (b"\x89PNG\r\n\x1a\n"
            + chunk(b"IHDR", struct.pack(">IIBBBBB", width, height, 8, 0, 0, 0, 0))
            + chunk(b"IDAT", zlib.compress(rows, level=1))
            + chunk(b"IEND", b""))


class ManualReleaseTests(unittest.TestCase):
    def setUp(self):
        workspace = TemporaryDirectory()
        self.addCleanup(workspace.cleanup)
        self.work = Path(workspace.name)
        self.image = self.work / "cover.png"
        self.image.write_bytes(png(0))
        today = datetime.now(ZoneInfo("Europe/Bucharest")).date().isoformat()
        self.entry = {
            "slug": SLUG, "title": "Local guide example", "description": "A local guide example.",
            "intro": "Introduction to a local guide.", "category": "City", "publish_date": today,
            "fact_checked_on": today, "image": self.image.name,
            "sections": [{"heading": heading, "paragraphs": ["Practical local detail."]}
                         for heading in ("Where", "When", "What to bring")],
            "sources": [{"label": "City Hall", "url": "https://www.pmb.ro/"}],
            "cover": {"kind": "ai_illustration", "author": "BucharestUA", "alt": "City park illustration",
                      "provenance": "Generated by the test fixture for BucharestUA"},
        }
        self.workspace = self.work / "queue"
        self.item = self.workspace / SLUG
        self.item.mkdir(parents=True)
        self.image = self.image.rename(self.item / self.image.name)
        self.draft = self.item / "draft.json"
        self.save_draft()

    def save_draft(self):
        self.draft.write_text(json.dumps(self.entry), encoding="utf-8")

    def run_cli(self, mode, directory=None, *flags):
        command = [sys.executable, str(ROOT / "scripts/publish_queue.py"), mode]
        if directory:
            command += [str(self.draft), "--output", str(self.item / directory), *flags]
        return subprocess.run(command, cwd=ROOT, capture_output=True, text=True)

    def preview_version(self):
        preview = self.run_cli("preview", "preview-1")
        self.assertEqual(preview.returncode, 0, preview.stderr)
        return preview.stdout.splitlines()[0].split()[1]

    def publish(self, version, output="release"):
        return self.run_cli("publish", output, "--preview", str(self.item / "preview-1"),
                            "--approved", version, "--approval-ref", "test-confirmation")

    def test_approved_bundle_contains_exact_preview_and_site_indexes(self):
        version = self.preview_version()
        release = self.publish(version)
        self.assertEqual(release.returncode, 0, release.stderr)
        preview_dir, release_dir = self.item / "preview-1", self.item / "release"
        page = SLUG + ".html"
        self.assertEqual((release_dir / page).read_bytes(), (preview_dir / page).read_bytes())
        for file in ("index.html", "articles.html", "sitemap.xml", "sitemap.txt", "feed.xml"):
            self.assertIn(page, (release_dir / file).read_text(encoding="utf-8"))
        record = json.loads((release_dir / "editorial/releases" / (SLUG + ".json")).read_text())
        self.assertEqual(record["version"], version)
        self.assertNotIn("approval_ref", record)
        self.assertEqual(len(record["approval_ref_sha256"]), 64)
        self.assertEqual(json.loads((preview_dir / "approval.json").read_text())["approval_ref"], "test-confirmation")
        self.assertNotIn("provenance", json.loads((release_dir / "media/assigned-images.json").read_text())[SLUG])
        self.assertTrue((release_dir / record["image_path"]).is_file())
        self.assertFalse((ROOT / page).exists())

    def test_stale_approval_rejected_for_changed_text_and_image(self):
        version = self.preview_version()
        self.entry["intro"] = "New article text."
        self.save_draft()
        self.assertNotEqual(self.publish(version, "edited").returncode, 0)
        self.assertFalse((self.item / "edited").exists())
        self.entry["intro"] = "Introduction to a local guide."
        self.save_draft()
        self.image.write_bytes(png(1))
        self.assertNotEqual(self.publish(version, "replaced").returncode, 0)
        self.assertFalse((self.item / "replaced").exists())

    def test_news_queue_and_explicit_approval(self):
        self.entry.update(type="news", event_date=self.entry["publish_date"], event_context="What changes for residents.")
        self.entry["sections"] = self.entry["sections"][:1]
        self.save_draft()
        version = self.preview_version()
        page = (self.item / "preview-1" / (SLUG + ".html")).read_text()
        self.assertIn('"@type": "NewsArticle"', page)
        self.assertIn("What changes for residents.", page)
        self.assertIn('href="https://www.pmb.ro/"', page)
        missing = self.run_cli("publish", "unapproved", "--approved", version, "--preview", str(self.item / "preview-1"))
        self.assertNotEqual(missing.returncode, 0)
        self.assertFalse((self.item / "unapproved").exists())
        command = [sys.executable, str(ROOT / "scripts/publish_queue.py"), "status", "--workspace", str(self.workspace)]
        self.assertIn("На согласовании", subprocess.check_output(command, text=True))
        self.assertEqual(self.publish(version).returncode, 0)
        self.assertIn("Одобрена", subprocess.check_output(command, text=True))
        self.entry["intro"] = "Revised news lead."
        self.save_draft()
        self.assertIn("Правки", subprocess.check_output(command, text=True))
        self.entry.pop("event_context")
        self.save_draft()
        self.assertNotEqual(self.run_cli("preview", "invalid-news").returncode, 0)

    def test_fabricated_preview_and_invalid_image_are_blocked(self):
        version = self.preview_version()
        preview_html = self.item / "preview-1" / (SLUG + ".html")
        preview_html.write_text("Tampered preview")
        self.assertNotEqual(self.publish(version).returncode, 0)
        self.image.write_bytes(png(0)[:-12])
        self.assertNotEqual(self.run_cli("preview", "broken-cover").returncode, 0)

    def test_legacy_default_and_drafts_without_sources_or_rights_are_blocked(self):
        self.assertNotEqual(self.run_cli("").returncode, 0)
        sources = self.entry.pop("sources")
        self.save_draft()
        self.assertNotEqual(self.run_cli("preview", "no-sources").returncode, 0)
        self.entry["sources"] = sources
        self.entry["cover"]["author"] = "Unknown"
        self.save_draft()
        self.assertNotEqual(self.run_cli("preview", "no-rights").returncode, 0)


if __name__ == "__main__":
    unittest.main()
